// Helper to compute total outfit price
export function getOutfitTotals(outfit) {
  if (!outfit || !outfit.hotspots) return { subtotal: 0, compareTotal: 0, savings: 0 };
  const subtotal = outfit.hotspots.reduce((sum, item) => sum + (item.price || 0), 0);
  const compareTotal = outfit.hotspots.reduce((sum, item) => sum + (item.compareAtPrice || item.price || 0), 0);
  const savings = Math.max(0, compareTotal - subtotal);
  return { subtotal, compareTotal, savings };
}

